#!/usr/bin/env python3
"""Extend existing GFX fonts, preserving every ASCII bitmap and metric exactly."""
import argparse
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "FramEink.Core/src/Fonts"
CONFIGS = [("FreeSansBold", 9), ("FreeSansBold", 12), ("FreeSansBold", 16), ("FreeSans", 12)]


def parse_font(source):
    source = re.sub(r"//[^\n]*", "", source)
    bitmap = re.search(r"Bitmaps\[\].*?=\s*\{(.*?)\};", source, re.S).group(1)
    data = bytes(int(value, 16) for value in re.findall(r"0x([0-9A-Fa-f]+)", bitmap))
    table = re.search(r"Glyphs\[\].*?=\s*\{(.*?)\};", source, re.S).group(1)
    glyphs = [tuple(map(int, re.findall(r"-?\d+", row))) for row in re.findall(r"\{([^{}]+)\}", table)]
    first, last, advance = re.search(r"Glyphs\s*,\s*0x([\da-fA-F]+),\s*0x([\da-fA-F]+),\s*(\d+)", source).groups()
    return data, glyphs, int(first, 16), int(last, 16), int(advance)


def glyph(font, code):
    data, glyphs, first, last, _ = font
    assert first <= code <= last
    offset, width, height, advance, x, y = glyphs[code - first]
    count = (width * height + 7) // 8
    assert offset + count <= len(data)
    return data[offset:offset + count], (width, height, advance, x, y)


def name_for(face, size):
    return face.replace("Free", "Calendar") + str(size) + "pt"


def check():
    for face, size in CONFIGS:
        original = parse_font((FONT_DIR / f"{face}{size}pt7b.h").read_text(encoding="latin-1"))
        name = name_for(face, size)
        extended = parse_font((FONT_DIR / (name + ".h")).read_text())
        assert extended[2:4] == (0x20, 0xFF)
        assert len(extended[1]) == 224
        assert extended[4] == original[4]
        for code in range(0x20, 0x7F):
            assert glyph(original, code) == glyph(extended, code), (name, code)
        for code in [0x80, 0xC8, 0xD6, 0xDC, 0xDF, 0xE8, 0xF6, 0xFC]:
            bitmap, metrics = glyph(extended, code)
            assert bitmap and metrics[0] and metrics[1], (name, code)
        for code in range(0x20, 0x100):
            glyph(extended, code)  # Every bitmap offset must be in bounds.
        print(f"{name}: ASCII unchanged, extended glyphs and offsets valid")


def generate(converter, freefont):
    mapping = (ROOT / "FramEink.Core/src/Calendar/CalendarText.h").read_text()
    table = re.search(r"calendarExtraCodepoints\[\]\s*=\s*\{(.*?)\}", mapping, re.S).group(1)
    extras = [int(code, 16) for code in re.findall(r"0x([0-9a-fA-F]+)", table)]
    for face, size in CONFIGS:
        original = parse_font((FONT_DIR / f"{face}{size}pt7b.h").read_text(encoding="latin-1"))
        def convert(first, last):
            return parse_font(subprocess.run([str(converter), str(freefont / (face + ".ttf")),
                str(size), str(first), str(last)], check=True, capture_output=True, text=True).stdout)
        latin = convert(0xA0, 0xFF)
        extra_fonts = [convert(code, code) for code in extras]
        data = bytearray()
        rows = []
        for code in range(0x20, 0x100):
            if code < 0x7F:
                bitmap, metrics = glyph(original, code)
            elif 0x80 <= code < 0x80 + len(extras):
                index = code - 0x80
                bitmap, metrics = glyph(extra_fonts[index], extras[index])
            elif code >= 0xA0:
                bitmap, metrics = glyph(latin, code)
            else:
                bitmap, metrics = b"", (0, 0, 0, 0, 0)
            rows.append((len(data), *metrics))
            data.extend(bitmap)
        assert len(data) < 65536
        name = name_for(face, size)
        output = ["#pragma once", "// Generated by tools/build_calendar_fonts.py; do not edit.",
            "// ASCII: existing project font. Extra glyphs: GNU FreeFont 20120503.",
            "// GPL-3.0-or-later with font exception; see Fonts/calendar-licenses/.",
            f"const uint8_t {name}Bitmaps[] PROGMEM = {{"]
        for offset in range(0, len(data), 12):
            output.append("  " + ", ".join(f"0x{value:02X}" for value in data[offset:offset + 12]) + ",")
        output.extend(["};", f"const GFXglyph {name}Glyphs[] PROGMEM = {{"])
        for code, row in enumerate(rows, 0x20):
            output.append("  {" + ", ".join(map(str, row)) + f"}}, // 0x{code:02X}")
        output.extend(["};", f"const GFXfont {name} PROGMEM = {{", f"  (uint8_t *){name}Bitmaps,",
            f"  (GFXglyph *){name}Glyphs, 0x20, 0xFF, {original[4]}", "};", ""])
        (FONT_DIR / (name + ".h")).write_text("\n".join(output))
    check()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--fontconvert", type=Path)
    parser.add_argument("--freefont-dir", type=Path)
    args = parser.parse_args()
    if args.check:
        check()
    elif args.fontconvert and args.freefont_dir:
        generate(args.fontconvert, args.freefont_dir)
    else:
        parser.error("Use --check or supply --fontconvert and --freefont-dir")
