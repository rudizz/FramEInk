#!/usr/bin/env python3
"""Embed the offline portal in flash. No downloads or third-party Python packages.

Normal use: python3 tools/build_portal_assets.py
Verify generated files: python3 tools/build_portal_assets.py --check
Import the pinned npm archive: --import-heic /path/to/heic-to-1.5.2.tgz
"""

import argparse
import base64
import gzip
import hashlib
from pathlib import Path
import tarfile

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "FramEink.Core/web"
HEADER = ROOT / "FramEink.Core/src/WiFiAccessPoint/PortalAssets.h"
HEIC_INTEGRITY = "8Fns+lZHAWmz5U5IUxDeXKwIf3foBoKNPLxxFY4B0MkLjNuomEIHCoDbDE+x/llFK3NCEO1cu4+n3iUKY+Svmw=="


def compress(data):
    result = bytearray(gzip.compress(data, compresslevel=9, mtime=0))
    result[9] = 255  # Stable gzip header across Python versions/operating systems.
    return bytes(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--import-heic", type=Path)
    args = parser.parse_args()
    if args.import_heic:
        archive_bytes = args.import_heic.read_bytes()
        integrity = base64.b64encode(hashlib.sha512(archive_bytes).digest()).decode()
        if integrity != HEIC_INTEGRITY:
            raise SystemExit("The HEIC archive does not match pinned heic-to 1.5.2.")
        vendor = WEB / "vendor"
        vendor.mkdir(exist_ok=True)
        with tarfile.open(args.import_heic, "r:gz") as archive:
            # Read specific members only; never extract archive-provided paths.
            decoder = archive.extractfile("package/dist/heic-to.min.js").read()
            license_text = archive.extractfile("package/LICENSE").read()
        (vendor / "heic-to-1.5.2.js.gz").write_bytes(compress(decoder))
        (vendor / "heic-to-LICENSE.txt").write_bytes(license_text)

    assets = [
        ("portalHtmlGzip", compress((WEB / "index.html").read_bytes())),
        ("portalJsGzip", compress((WEB / "portal.js").read_bytes())),
        ("heicToGzip", (WEB / "vendor/heic-to-1.5.2.js.gz").read_bytes()),
    ]
    lines = ["// Generated by tools/build_portal_assets.py. Do not edit.",
             "#pragma once", "#include <Arduino.h>", "", "namespace frameink {", ""]
    for name, data in assets:
        lines.append(f"static const uint8_t {name}[] PROGMEM = {{")
        for start in range(0, len(data), 24):
            lines.append("    " + ",".join(f"0x{byte:02x}" for byte in data[start:start + 24]) + ",")
        lines.extend(["};", ""])
        print(f"{name}: {len(data):,} compressed bytes")
    lines.extend(["} // namespace frameink", ""])
    output = "\n".join(lines).encode()
    if args.check:
        if not HEADER.exists() or HEADER.read_bytes() != output:
            raise SystemExit("PortalAssets.h is stale. Run python3 tools/build_portal_assets.py.")
    else:
        HEADER.write_bytes(output)


if __name__ == "__main__":
    main()
